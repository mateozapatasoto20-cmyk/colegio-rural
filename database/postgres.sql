-- =========================================================
-- Sistema académico con alertas - Colegio Rural (versión 2)
-- VERSIÓN PostgreSQL (para cuando el colegio cambie de base de datos).
-- Primero crea la base:  CREATE DATABASE colegio_rural;  y luego ejecuta este archivo dentro de ella.
-- =========================================================

CREATE TABLE estudiantes (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombres VARCHAR(60) NOT NULL,
  apellidos VARCHAR(60) NOT NULL,
  grado VARCHAR(30) NOT NULL,
  seccion VARCHAR(5) NOT NULL,
  dni VARCHAR(8) NOT NULL UNIQUE,
  activo SMALLINT NOT NULL DEFAULT 1
);
CREATE TABLE docentes (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombres VARCHAR(60) NOT NULL,
  apellidos VARCHAR(60) NOT NULL,
  especialidad VARCHAR(60) NOT NULL
);
CREATE TABLE cursos (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(60) NOT NULL,
  grado VARCHAR(30) NOT NULL,
  seccion VARCHAR(5) NOT NULL,
  periodo VARCHAR(15) NOT NULL
);
CREATE TABLE docente_cursos (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  docente_id INT NOT NULL,
  curso_id INT NOT NULL,
  periodo VARCHAR(15) NOT NULL,
  FOREIGN KEY (docente_id) REFERENCES docentes(id) ON DELETE CASCADE,
  FOREIGN KEY (curso_id) REFERENCES cursos(id) ON DELETE CASCADE
);
CREATE TABLE usuarios (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(30) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  rol VARCHAR(20) NOT NULL CHECK (rol IN ('admin','coordinador','docente','alumno')),
  nombre VARCHAR(80) NOT NULL,
  activo SMALLINT NOT NULL DEFAULT 1,
  estudiante_id INT NULL,
  FOREIGN KEY (estudiante_id) REFERENCES estudiantes(id) ON DELETE SET NULL
);
CREATE TABLE calificaciones (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estudiante_id INT NOT NULL,
  curso VARCHAR(60) NOT NULL,
  nota DECIMAL(4,1) NOT NULL,
  asistencia DECIMAL(5,1) NOT NULL,
  FOREIGN KEY (estudiante_id) REFERENCES estudiantes(id) ON DELETE CASCADE
);
CREATE TABLE alertas (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estudiante_id INT NOT NULL,
  mensaje TEXT NOT NULL,
  tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('nota','asistencia','manual')),
  estado VARCHAR(20) NOT NULL CHECK (estado IN ('activa','resuelta')) DEFAULT 'activa',
  creada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (estudiante_id) REFERENCES estudiantes(id) ON DELETE CASCADE
);
CREATE TABLE logs (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario VARCHAR(30) NOT NULL,
  accion VARCHAR(150) NOT NULL,
  creado TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE asistencias (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estudiante_id INT NOT NULL,
  curso_id INT NOT NULL,
  fecha DATE NOT NULL,
  estado VARCHAR(20) NOT NULL CHECK (estado IN ('presente','tardanza','falta','justificada')),
  UNIQUE (estudiante_id, curso_id, fecha),
  FOREIGN KEY (estudiante_id) REFERENCES estudiantes(id) ON DELETE CASCADE,
  FOREIGN KEY (curso_id) REFERENCES cursos(id) ON DELETE CASCADE
);
CREATE TABLE anuncios (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo VARCHAR(80) NOT NULL,
  mensaje TEXT NOT NULL,
  audiencia VARCHAR(20) NOT NULL CHECK (audiencia IN ('todos','docentes','alumnos')) DEFAULT 'todos',
  autor VARCHAR(80) NOT NULL,
  creado TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE configuracion (
  clave VARCHAR(40) PRIMARY KEY,
  valor VARCHAR(100) NOT NULL
);

